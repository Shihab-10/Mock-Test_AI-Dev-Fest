export function formatValidationIssue(issue: ValidationIssue, language: Language): string {
  const template = validationMessages[issue.code][language === 'en' ? 0 : 1]
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => String(issue.params?.[key] ?? ''))
}